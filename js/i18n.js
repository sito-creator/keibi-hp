const STORAGE_KEY = "ntps_lang";
const LANG_CYCLE = ["ja", "en", "ko", "zh", "ar"];

function getCurrentLang() {
    // URLパラメータ ?hl=xx があればその言語を優先
    const urlParams = new URLSearchParams(window.location.search);
    const urlLang = urlParams.get('hl');
    if (urlLang && LANG_CYCLE.includes(urlLang)) {
        localStorage.setItem(STORAGE_KEY, urlLang);
        return urlLang;
    }
    return localStorage.getItem(STORAGE_KEY) || "ja";
}

function setLang(lang) {
    localStorage.setItem(STORAGE_KEY, lang);
    applyLang(lang);
}

function applyLang(lang) {
    // Update toggle button text
    const labels = { ja: "JA", en: "EN", ko: "KO", zh: "ZH", ar: "AR" };
    document.querySelectorAll("#lang-toggle span, .header__lang span").forEach(el => {
        el.textContent = labels[lang] || lang.toUpperCase();
    });

    // Get translation dict for current language
    const dict = translations[lang];

    // Translate elements with data-i18n
    document.querySelectorAll("[data-i18n]").forEach(el => {
        const key = el.getAttribute("data-i18n");

        if (lang !== "ja" && dict && dict[key]) {
            if (!el.getAttribute("data-i18n-ja")) {
                if (el.tagName === "OPTION") {
                    el.setAttribute("data-i18n-ja", el.textContent);
                } else {
                    el.setAttribute("data-i18n-ja", el.innerHTML);
                }
            }
            if (el.tagName === "OPTION") {
                el.textContent = dict[key];
            } else {
                el.innerHTML = dict[key];
            }
        } else if (lang === "ja") {
            const ja = el.getAttribute("data-i18n-ja");
            if (ja) {
                if (el.tagName === "OPTION") {
                    el.textContent = ja;
                } else {
                    el.innerHTML = ja;
                }
            }
        }
    });

    // Translate placeholders with data-i18n-ph
    document.querySelectorAll("[data-i18n-ph]").forEach(el => {
        const key = el.getAttribute("data-i18n-ph");

        if (lang !== "ja" && dict && dict[key]) {
            if (!el.getAttribute("data-i18n-ph-ja")) {
                el.setAttribute("data-i18n-ph-ja", el.getAttribute("placeholder"));
            }
            el.setAttribute("placeholder", dict[key]);
        } else if (lang === "ja") {
            const ja = el.getAttribute("data-i18n-ph-ja");
            if (ja) {
                el.setAttribute("placeholder", ja);
            }
        }
    });

    // RTL support for Arabic
    const isRTL = lang === "ar";
    document.documentElement.dir = isRTL ? "rtl" : "ltr";
    document.body.classList.toggle("rtl", isRTL);

    // Update html lang
    const langMap = { ja: "ja", en: "en", ko: "ko", zh: "zh-Hans", ar: "ar" };
    document.documentElement.lang = langMap[lang] || lang;
}

function toggleLang() {
    const current = getCurrentLang();
    const idx = LANG_CYCLE.indexOf(current);
    const next = LANG_CYCLE[(idx + 1) % LANG_CYCLE.length];
    setLang(next);
}

document.addEventListener("DOMContentLoaded", () => {
    const lang = getCurrentLang();
    if (lang !== "ja") {
        applyLang(lang);
    }

    document.querySelectorAll("#lang-toggle").forEach(btn => {
        btn.addEventListener("click", (e) => {
            e.preventDefault();
            e.stopPropagation();
            toggleLang();
        });
    });
});
